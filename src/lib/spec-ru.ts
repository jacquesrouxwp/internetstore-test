const LETTER = "A-Za-z0-9А-Яа-яЁёІіЇїЄєҐґ'’";
// "Так" (yes) has no Ukrainian-only letters, so yes/no values are matched whole.
const YES_NO = /^(?:Так|Ні)(?:\s*\/\s*(?:Так|Ні))*$/;
const YES_AT_START = /^Так(?=[\s,.])/;

const RU_VALUE_RULES = RU_VALUE_WORDS.map(([uk, ru]) => ({
  // The phrases are plain words and dashes — nothing to escape
  re: new RegExp(`(?<![${LETTER}])${uk}(?![${LETTER}])`, "gi"),
  ru,
}));

const keepCase = (found: string, ru: string) =>
  found[0] !== found[0].toLowerCase() ? ru[0].toUpperCase() + ru.slice(1) : ru;

/** A spec value for the Russian page, or the original when it cannot be made Russian. */
export function ruSpecValue(value: string): string {
  const trimmed = value.trim();
  if (YES_NO.test(trimmed)) return trimmed.replace(/Так/g, "Да").replace(/Ні/g, "Нет");
  const yes = value.replace(YES_AT_START, "Да");
  if (!UKRAINIAN_LETTERS.test(yes)) return yes;
  let out = yes;
  for (const { re, ru } of RU_VALUE_RULES) out = out.replace(re, (m) => keepCase(m, ru));
  return UKRAINIAN_LETTERS.test(out) ? value : out;
}

// "Вага, гр" is spelled with letters Russian has too, so names are matched as well
const UKRAINIAN_LABELS = Object.keys(RU_SPEC_LABELS);

/**
 * Drops the sentences of a Russian text that are written (partly) in
 * Ukrainian — the old generated descriptions quote Ukrainian spec names
 * ("Также в спецификации указано: Вага, гр — 100.").
 */
export function dropUkrainianSentences(text: string): string {
  // Split only where a sentence mark is followed by a space: "F1.1", "2.4 GHz" stay whole.
  return text
    .replace(/([.!?])\s+/g, "$1\n")
    .split("\n")
    .map((s) => s.trim())
    .filter((s) => s && !UKRAINIAN_LETTERS.test(s) && !UKRAINIAN_LABELS.some((l) => s.includes(l)))
    .join(" ");
}
