type Props = { params: Promise<{ locale: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { locale } = await params;
  const isRu = locale === "ru";
  const title = isRu
    ? "Возврат и обмен товара | Pro-Optics"
    : "Повернення та обмін товару | Pro-Optics";
  const description = isRu
    ? "Условия возврата и обмена в Pro-Optics: 14 дней для товара надлежащего качества, брак по гарантии, оформление через Новую Почту. Тел. 097 493 21 03."
    : "Умови повернення та обміну в Pro-Optics: 14 днів для товару належної якості, брак за гарантією, оформлення через Нову Пошту. Тел. 097 493 21 03.";
  const path = isRu ? "/ru/returns" : "/returns";
  return {
    title,
    description,
    alternates: { canonical: absoluteUrl(path) },
    openGraph: { title, description, url: absoluteUrl(path) },
  };
}

function PhoneLink({ source }: { source: "returns" }) {
  return (
    <ConsultTrackLink
      channel="phone"
      source={source}
      href={STORE_PHONE_TEL}
      className="font-semibold text-[var(--accent)] hover:underline"
    >
      {STORE_PHONE_DISPLAY}
    </ConsultTrackLink>
  );
}

