-- Public read published only; write via service_role

alter table posts add column if not exists category text;
alter table posts add column if not exists meta_title_uk text;
alter table posts add column if not exists meta_title_ru text;
alter table posts add column if not exists meta_description_uk text;
alter table posts add column if not exists meta_description_ru text;
alter table posts add column if not exists created_at timestamptz default now();
alter table posts add column if not exists updated_at timestamptz default now();

create index if not exists posts_published_at_idx on posts(published_at desc nulls last);
create index if not exists posts_category_idx on posts(category);
create index if not exists posts_slug_idx on posts(slug);

alter table posts enable row level security;

drop policy if exists "public read published posts" on posts;
create policy "public read published posts"
  on posts for select
  using (published = true);

